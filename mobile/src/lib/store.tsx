import AsyncStorage from "@react-native-async-storage/async-storage";
import type { Session } from "@supabase/supabase-js";
import { createContext, useCallback, useContext, useEffect, useMemo, useRef, useState, type ReactNode } from "react";
import { applyFeedback, emptyProfile, TasteProfile, type Feedback } from "@shared/profile";
import { PlanSpec, type Itinerary, type PlanRequest } from "@shared/schema";
import { persistSpec } from "@shared/storage";
import type { EventName } from "@shared/analytics";
import type { SignalBatch } from "@shared/polls";
import { api, type Status } from "./api";
import { supabase } from "./auth";

/**
 * Device-first state. Plans are stored as specs (place IDs + user choices), never as
 * provider content; opening a plan re-hydrates current venue data from the server.
 */
export type PlanEntry = {
  spec: PlanSpec;
  saved: boolean;
  createdAt: string;
  feedback?: Feedback;
  /** Display-only snapshot for lists (title/area/time/stop count), no provider content. */
  meta: { title: string; area: string; date: string; startTime: string; stops: number; demo: boolean };
};
type State = {
  ready: boolean;
  profile: TasteProfile;
  plans: Record<string, PlanEntry>;
  installId: string;
  status: Status | null;
  session: Session | null;
};
type Store = State & {
  setProfile: (p: TasteProfile) => void;
  /** Live itineraries for this app session (memory only). */
  live: Record<string, Itinerary>;
  remember: (plan: Itinerary, opts?: { saved?: boolean }) => void;
  setSaved: (id: string, saved: boolean) => void;
  remove: (id: string) => void;
  submitFeedback: (plan: Itinerary, feedback: Feedback) => Promise<"device" | "account">;
  /** Request waiting to be generated by the plan screen. */
  pending: { current: PlanRequest | null };
  track: (name: EventName, props?: Record<string, string | number | boolean>) => void;
  /** Explicit, anonymous community reactions (polls, thumbs, plan pulse). */
  react: (source: SignalBatch["source"], entries: SignalBatch["entries"], reason?: SignalBatch["reason"]) => void;
  refreshStatus: () => Promise<void>;
  resetDevice: () => Promise<void>;
  demo: boolean;
};

const Ctx = createContext<Store | null>(null);
const KEYS = { profile: "whimway:profile", plans: "whimway:plans:v1", install: "whimway:install" };
const randomId = () =>
  "xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx".replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0;
    return (c === "x" ? r : (r & 0x3) | 0x8).toString(16);
  });

function metaOf(plan: Itinerary | PlanSpec): PlanEntry["meta"] {
  return {
    title: plan.title,
    area: plan.request.location.name,
    date: plan.request.date,
    startTime: plan.request.startTime,
    stops: plan.stops.length,
    demo: plan.demo,
  };
}

export function StoreProvider({ children }: { children: ReactNode }) {
  const [state, setState] = useState<State>({
    ready: false,
    profile: emptyProfile(),
    plans: {},
    installId: "",
    status: null,
    session: null,
  });
  const [live, setLive] = useState<Record<string, Itinerary>>({});
  const pending = useRef<PlanRequest | null>(null);
  const stateRef = useRef(state);
  stateRef.current = state;

  // Load persisted state once.
  useEffect(() => {
    (async () => {
      const [rawProfile, rawPlans, rawInstall] = await Promise.all([
        AsyncStorage.getItem(KEYS.profile).catch(() => null),
        AsyncStorage.getItem(KEYS.plans).catch(() => null),
        AsyncStorage.getItem(KEYS.install).catch(() => null),
      ]);
      const parsedProfile = TasteProfile.safeParse(rawProfile ? JSON.parse(rawProfile) : {});
      const plans: Record<string, PlanEntry> = {};
      try {
        for (const [id, entry] of Object.entries(JSON.parse(rawPlans ?? "{}") as Record<string, PlanEntry>)) {
          const spec = PlanSpec.safeParse(entry.spec);
          if (spec.success) plans[id] = { ...entry, spec: spec.data };
        }
      } catch {
        // Corrupt storage: start fresh rather than crash.
      }
      const installId = rawInstall ?? randomId();
      if (!rawInstall) void AsyncStorage.setItem(KEYS.install, installId);
      const session = supabase ? (await supabase.auth.getSession()).data.session : null;
      setState((s) => ({
        ...s,
        ready: true,
        profile: parsedProfile.success ? parsedProfile.data : emptyProfile(),
        plans,
        installId,
        session,
      }));
    })();
    const sub = supabase?.auth.onAuthStateChange((_event, session) => setState((s) => ({ ...s, session })));
    return () => sub?.data.subscription.unsubscribe();
  }, []);

  const persistPlans = (plans: Record<string, PlanEntry>) => {
    void AsyncStorage.setItem(KEYS.plans, JSON.stringify(plans)).catch(() => undefined);
  };

  const track = useCallback<Store["track"]>((name, props = {}) => {
    const s = stateRef.current;
    if (!s.profile.analytics || !s.installId) return;
    void api("events", { name, installId: s.installId, props }).catch(() => undefined);
  }, []);

  const react = useCallback<Store["react"]>((source, entries, reason) => {
    const s = stateRef.current;
    if (!s.installId || !entries.length) return;
    void api("signals", { installId: s.installId, source, reason, entries: entries.slice(0, 16) }).catch(() => undefined);
  }, []);

  const setProfile = useCallback((profile: TasteProfile) => {
    // Apply immediately so anything tracked in the same tick sees the new consent and stats.
    stateRef.current = { ...stateRef.current, profile };
    setState((s) => ({ ...s, profile }));
    void AsyncStorage.setItem(KEYS.profile, JSON.stringify(profile)).catch(() => undefined);
    // Sync to the account when signed in; the device copy stays authoritative offline.
    if (stateRef.current.session) void api("taste", profile).catch(() => undefined);
  }, []);

  const remember = useCallback<Store["remember"]>((plan, opts = {}) => {
    setLive((l) => ({ ...l, [plan.id]: plan }));
    setState((s) => {
      const existing = s.plans[plan.id];
      const entry: PlanEntry = {
        spec: persistSpec(PlanSpec.parse(plan)),
        saved: opts.saved ?? existing?.saved ?? false,
        createdAt: existing?.createdAt ?? new Date().toISOString(),
        feedback: existing?.feedback,
        meta: metaOf(plan),
      };
      // Keep every saved plan, plus the 12 most recent unsaved ones.
      const all = { ...s.plans, [plan.id]: entry };
      const unsaved = Object.entries(all)
        .filter(([, e]) => !e.saved)
        .sort((a, b) => b[1].createdAt.localeCompare(a[1].createdAt));
      for (const [id] of unsaved.slice(12)) delete all[id];
      persistPlans(all);
      return { ...s, plans: all };
    });
  }, []);

  const setSaved = useCallback((id: string, saved: boolean) => {
    setState((s) => {
      if (!s.plans[id]) return s;
      const plans = { ...s.plans, [id]: { ...s.plans[id], saved } };
      persistPlans(plans);
      return { ...s, plans };
    });
  }, []);

  const remove = useCallback((id: string) => {
    setState((s) => {
      const plans = { ...s.plans };
      delete plans[id];
      persistPlans(plans);
      return { ...s, plans };
    });
    if (stateRef.current.session) void api(`plans/${id}`, undefined, { method: "DELETE" }).catch(() => undefined);
  }, []);

  const submitFeedback = useCallback<Store["submitFeedback"]>(async (plan, feedback) => {
    const s = stateRef.current;
    const categories = plan.stops.map((st) => st.place.category);
    setProfile(applyFeedback(s.profile, feedback, categories));
    setState((cur) => {
      const entry = cur.plans[plan.id];
      if (!entry) return cur;
      const plans = { ...cur.plans, [plan.id]: { ...entry, feedback } };
      persistPlans(plans);
      return { ...cur, plans };
    });
    track("feedback_submitted", { went: feedback.went, rating: feedback.rating ?? 0 });
    try {
      return (await api<{ stored: "device" | "account" }>("feedback", { ...feedback, installId: s.installId })).stored;
    } catch {
      return "device";
    }
  }, [setProfile, track]);

  const refreshStatus = useCallback(async () => {
    try {
      const status = await api<Status>("status");
      setState((s) => ({ ...s, status }));
    } catch {
      setState((s) => ({ ...s, status: null }));
    }
  }, []);
  useEffect(() => {
    void refreshStatus();
  }, [refreshStatus]);

  const resetDevice = useCallback(async () => {
    await AsyncStorage.multiRemove([KEYS.profile, KEYS.plans]);
    setLive({});
    setState((s) => ({ ...s, profile: emptyProfile(), plans: {} }));
  }, []);

  const demo = Boolean(state.status && (!state.status.places || !state.status.ai) && state.status.demo);
  const value = useMemo<Store>(
    () => ({ ...state, live, setProfile, remember, setSaved, remove, submitFeedback, pending, track, react, refreshStatus, resetDevice, demo }),
    [state, live, setProfile, remember, setSaved, remove, submitFeedback, track, react, refreshStatus, resetDevice, demo],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useStore() {
  const store = useContext(Ctx);
  if (!store) throw new Error("useStore must be used inside StoreProvider");
  return store;
}
