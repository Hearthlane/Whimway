// Captures store screenshots (1290x2796, iPhone 6.7") from the web build.
// Usage: node scripts/store-screenshots.mjs [appUrl]   (API in demo mode + serve-web running)
import { chromium } from "@playwright/test";
const base = process.argv[2] ?? "http://localhost:8090";
const out = new URL("../store/screenshots/", import.meta.url).pathname;
const b = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH });
const p = await (await b.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true })).newPage();
const shot = async (name) => p.screenshot({ path: `${out}${name}.png` });
await p.goto(`${base}/`, { waitUntil: "networkidle" });
await p.waitForTimeout(2800);
await shot("01-welcome");
await p.getByTestId("onboarding-next").click();
await p.getByTestId("who-partner").click();
await p.getByTestId("onboarding-next").click();
await p.getByTestId("vibe-romantic").click();
await p.getByTestId("vibe-adventurous").click();
for (let i = 0; i < 5; i++) await p.getByTestId("onboarding-next").click();
await p.getByTestId("persona").waitFor({ timeout: 15000 });
await p.waitForTimeout(1500);
await shot("02-personality");
await p.getByTestId("onboarding-next").click();
await p.getByTestId("plus-skip").click();
await p.getByTestId("prompt-input").fill("Saturday night with my girlfriend, $100 total, romantic but a little adventurous");
await p.waitForTimeout(600);
await shot("03-say-it");
await p.getByTestId("plan-it").click();
await p.getByTestId("plan-title").waitFor({ timeout: 60000 });
await p.waitForTimeout(1500);
await shot("04-plan");
await p.getByTestId("stop-1").scrollIntoViewIfNeeded();
await p.mouse.wheel(0, 260);
await p.waitForTimeout(700);
await shot("05-timeline");
await p.getByTestId("magic-edit").click();
await p.getByTestId("magic-input").fill("Keep the first two stops, change the last one");
await p.waitForTimeout(700);
await shot("06-magic-edit");
await b.close();
console.log("Saved 6 screenshots to", out);
