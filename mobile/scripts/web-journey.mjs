// End-to-end journey for the Expo app's web build (see README › Verify the app).
// Usage: node scripts/web-journey.mjs [appUrl] [screenshotDir]
// Requires: API on :3000 in demo mode, `node scripts/serve-web.mjs` serving dist/ on :8090.
import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { chromium, devices } from "@playwright/test";
const base = process.argv[2] ?? "http://localhost:8090";
const out = process.argv[3] ?? "journey-shots";
mkdirSync(out, { recursive: true });
const shot = async (p, name) => p.screenshot({ path: `${out}/${name}.png`, fullPage: false });
(async () => {
  const b = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH });
  const ctx = await b.newContext({ ...devices['iPhone 13'], geolocation: { latitude: 43.6487, longitude: -79.4208 }, permissions: ['geolocation'] });
  const p = await ctx.newPage();
  const errors = [];
  const apiCalls = [];
  p.on('pageerror', e => errors.push('pageerror: ' + e.message));
  p.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  p.on('response', r => { if (r.url().includes('/api/')) apiCalls.push(`${r.request().method()} ${new URL(r.url()).pathname} ${r.status()}`); });
  const t0 = Date.now();
  await p.goto(`${base}/`, { waitUntil: 'networkidle' });
  await p.getByTestId('onboarding-next').waitFor();
  await p.waitForTimeout(2600);
  await shot(p, '01-welcome');
  await p.getByTestId('onboarding-next').click();
  await p.getByTestId('who-partner').click();
  await p.getByTestId('onboarding-next').click();
  await p.getByTestId('vibe-romantic').click();
  await p.getByTestId('vibe-adventurous').click();
  await shot(p, '03-vibes');
  await p.getByTestId('onboarding-next').click();
  await p.getByTestId('onboarding-next').click();
  await p.getByTestId('onboarding-next').click();
  await p.getByTestId('area-queen-west').click();
  await p.getByTestId('onboarding-next').click();
  await p.getByLabel('What should we call you?').fill('Sam').catch(() => {});
  await p.getByTestId('onboarding-next').click();
  await p.waitForTimeout(1400);
  const personaName = await p.getByTestId('persona').innerText();
  await shot(p, '03b-reveal');
  await p.getByTestId('onboarding-next').click();
  await p.getByTestId('prompt-input').waitFor();
  const onboardMs = Date.now() - t0;
  // Poll
  await p.getByTestId('poll-card').scrollIntoViewIfNeeded();
  await shot(p, '04-poll');
  await p.getByTestId('poll-b').click();
  await p.waitForTimeout(700);
  await p.getByTestId('poll-card').screenshot({ path: `${out}/05-poll-result.png` });
  const pollText = await p.getByTestId('poll-card').innerText();
  await p.getByTestId('poll-next').click();
  await p.waitForTimeout(300);
  const nextPollText = await p.getByTestId('poll-card').innerText();
  await p.evaluate(() => window.scrollTo(0, 0));
  const prompt = "Plan a spontaneous Saturday night with my girlfriend. We have $100 total, we're near Toronto, we want something romantic but adventurous, and we don't want to drive too far.";
  await p.getByTestId('prompt-input').fill(prompt);
  await p.waitForTimeout(300);
  const chips = (await p.locator('[data-testid^="chip-"]').allInnerTexts()).map(s => s.trim());
  await shot(p, '06-home-heard');
  const g0 = Date.now();
  await p.getByTestId('plan-it').click();
  await p.getByTestId('plan-title').waitFor({ timeout: 60000 });
  const genMs = Date.now() - g0;
  await p.waitForTimeout(600);
  await shot(p, '07-plan-top');
  const title = await p.getByTestId('plan-title').innerText();
  const stopsBefore = await p.locator('[data-testid^="stop-"]').allInnerTexts();
  await p.screenshot({ path: `${out}/08-plan-full.png`, fullPage: true });
  // Plan pulse: thumbs down -> reason -> fix
  await p.getByTestId('pulse-down').scrollIntoViewIfNeeded();
  await p.getByTestId('pulse-down').click();
  await p.getByText('Too pricey').click();
  await p.waitForTimeout(300);
  await p.getByTestId('pulse-reasons').screenshot({ path: `${out}/09-pulse.png` });
  // Stop reaction
  await p.getByTestId('stop-1').locator('[role="button"]').first().click();
  await p.waitForTimeout(300);
  await p.getByTestId('react-up-1').click();
  await p.getByTestId('stop-1').screenshot({ path: `${out}/10-stop-reacted.png` });
  // Magic edit
  await p.getByTestId('magic-edit').click();
  await p.getByTestId('magic-input').fill('Keep the first two stops, but change the last one');
  await p.waitForTimeout(300);
  await shot(p, '11-magic-sheet');
  await p.getByTestId('magic-apply').click();
  await p.getByText('Undo').waitFor({ timeout: 30000 });
  const toast = await p.getByText('Undo').locator('..').innerText();
  await p.waitForTimeout(400);
  const stopsAfter = await p.locator('[data-testid^="stop-"]').allInnerTexts();
  await shot(p, '12-after-edit');
  // Favourite the first stop (its card is still expanded from the reaction step).
  const favName = (await p.getByTestId('stop-1').innerText()).split('\n').filter(Boolean)[3];
  await p.getByTestId('stop-1').getByRole('button', { name: 'Save place' }).click();
  await p.getByLabel('Save plan').click();
  await p.waitForTimeout(300);
  await p.getByLabel('Share plan').click();
  const link = await p.getByTestId('share-link').inputValue({ timeout: 10000 });
  await shot(p, '13-share');
  await p.getByLabel('Close').last().click();
  await p.getByTestId('feedback-open').click();
  await p.getByText('Yes, all of it').click();
  await p.getByLabel('5 stars').click();
  await p.getByLabel(/^Loved /).first().click();
  await shot(p, '14-feedback');
  await p.getByTestId('feedback-submit').click();
  await p.getByText(/Thanks!/).waitFor({ timeout: 10000 });
  await p.goto(`${base}/saved`, { waitUntil: 'networkidle' });
  await p.waitForTimeout(500);
  await shot(p, '15-saved');
  await p.goto(`${base}/profile`, { waitUntil: 'networkidle' });
  await p.waitForTimeout(500);
  await shot(p, '16-profile');
  // Favourites → plan around it
  const favListed = (await p.getByTestId('favourite').allInnerTexts()).join(' ');
  await p.getByRole('button', { name: 'Plan around it' }).first().click();
  await p.getByTestId('plan-title').waitFor({ timeout: 60000 });
  await p.waitForTimeout(400);
  const anchoredStops = (await p.locator('[data-testid^="stop-"]').allInnerTexts()).join(' ');
  await shot(p, '17-plan-around-favourite');
  // Open a shared link inside the app
  await p.goto(`${base}/import`, { waitUntil: 'networkidle' });
  await p.getByTestId('import-link').fill(link);
  await p.getByTestId('import-open').click();
  await p.getByTestId('plan-title').waitFor({ timeout: 60000 });
  const importedTitle = await p.getByTestId('plan-title').innerText();
  // Near me
  await p.goto(`${base}/`, { waitUntil: 'networkidle' });
  await p.getByTestId('chip-area').click();
  await p.getByTestId('near-me').click();
  await p.getByText('Using your location').waitFor({ timeout: 10000 });
  await p.getByRole('button', { name: 'Done' }).click();
  const areaChip = (await p.getByTestId('chip-area').innerText()).trim();
  await shot(p, '18-near-me');
  const r = await (await b.newContext({ ...devices['iPhone 13'] })).newPage();
  r.on('pageerror', e => errors.push('recipient pageerror: ' + e.message));
  await r.goto(link, { waitUntil: 'networkidle' });
  await r.waitForTimeout(2500);
  await r.screenshot({ path: `${out}/17-recipient.png` });
  const recipientTitle = (await r.locator('h1').first().innerText().catch(() => '')).slice(0, 80);
  const summarize = a => a.map(s => s.split('\n').filter(Boolean).slice(0, 4).join(' | '));
  // Assertions: the core journey must hold end to end.
  assert.deepEqual(errors, [], "browser errors");
  assert.ok(chips.some((c) => c.includes("$100 total · $50/person")), "budget understood");
  assert.ok(chips.some((c) => c.includes("With your partner")), "companion understood");
  assert.ok(stopsBefore.length >= 2 && stopsBefore.length <= 4, "2–4 stops");
  assert.equal(stopsAfter.length, stopsBefore.length, "magic edit keeps the stop count");
  assert.deepEqual(summarize(stopsAfter).slice(0, -1), summarize(stopsBefore).slice(0, -1), "kept stops untouched");
  assert.ok(link.includes("/p#"), "account-free share link");
  assert.ok(favListed.includes(favName), `favourite listed (${favName})`);
  assert.ok(anchoredStops.includes(favName), "plan built around the favourite");
  assert.equal(importedTitle, title, "shared link opens inside the app");
  assert.ok(areaChip.endsWith("Near you"), "near me sets the planning area");
  assert.equal(recipientTitle, title, "recipient sees the plan");
  for (const call of ["POST /api/polls/answer 200", "POST /api/signals 200", "POST /api/magic-edit 200", "POST /api/feedback 200"])
    assert.ok(apiCalls.includes(call), call);
  assert.equal(personaName, 'Romantic Adventurer', 'personality reveal');
  console.log(JSON.stringify({ personaName, favName, areaChip, importedTitle, onboardMs, genMs, title, chips, pollText: pollText.replace(/\n+/g, ' / '), nextPollText: nextPollText.split('\n').filter(Boolean).slice(0, 2).join(' / '), stopsBefore: summarize(stopsBefore), stopsAfter: summarize(stopsAfter), toast: toast.replace(/\n/g, ' '), linkLen: link.length, recipientTitle, apiCalls: [...new Set(apiCalls)], errors }, null, 2));
  await b.close();
})().catch(e => { console.error('JOURNEY FAILED', e.message.split('\n').slice(0, 6).join(' // ')); process.exit(1); });
